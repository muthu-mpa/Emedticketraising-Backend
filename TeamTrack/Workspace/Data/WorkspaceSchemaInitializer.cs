using Microsoft.EntityFrameworkCore;

namespace TeamTrack.Workspace.Data
{
    /// <summary>Tracks whether the ws_ schema is usable. Registered only when Features:Workspace is on.</summary>
    public class WorkspaceState
    {
        public bool SchemaReady { get; set; }
        public string? SchemaError { get; set; }
    }

    public static class WorkspaceSchemaInitializer
    {
        // Run through ExecuteSqlRawAsync, which treats { and } as format placeholders: never put braces in this script.
        public const string Sql = @"
            CREATE TABLE IF NOT EXISTS ws_campaigns (
                id integer GENERATED BY DEFAULT AS IDENTITY,
                title text NOT NULL,
                client_name text NOT NULL DEFAULT '',
                contact_name text NOT NULL DEFAULT '',
                client_email text NOT NULL DEFAULT '',
                subject text NOT NULL DEFAULT '',
                body text NOT NULL DEFAULT '',
                status text NOT NULL DEFAULT 'draft',
                manager_note text,
                created_by_user_id integer NOT NULL,
                created_at timestamp with time zone NOT NULL,
                updated_at timestamp with time zone NOT NULL,
                sent_at timestamp with time zone,
                CONSTRAINT ""PK_ws_campaigns"" PRIMARY KEY (id),
                CONSTRAINT ""FK_ws_campaigns_users_created_by_user_id"" FOREIGN KEY (created_by_user_id) REFERENCES users (id) ON DELETE RESTRICT,
                CONSTRAINT ""CK_ws_campaigns_status"" CHECK (status IN ('draft','pending','approved','sending','sent'))
            );
            CREATE INDEX IF NOT EXISTS ""IX_ws_campaigns_status"" ON ws_campaigns (status);
            CREATE INDEX IF NOT EXISTS ""IX_ws_campaigns_created_by_user_id"" ON ws_campaigns (created_by_user_id);
            -- 'sending' was added after the first release; refresh the constraint on databases that already have the table
            ALTER TABLE ws_campaigns DROP CONSTRAINT IF EXISTS ""CK_ws_campaigns_status"";
            ALTER TABLE ws_campaigns ADD CONSTRAINT ""CK_ws_campaigns_status"" CHECK (status IN ('draft','pending','approved','sending','sent'));

            CREATE TABLE IF NOT EXISTS ws_campaign_history (
                id integer GENERATED BY DEFAULT AS IDENTITY,
                campaign_id integer NOT NULL,
                user_id integer NOT NULL,
                action text NOT NULL,
                note text,
                created_at timestamp with time zone NOT NULL,
                CONSTRAINT ""PK_ws_campaign_history"" PRIMARY KEY (id),
                CONSTRAINT ""FK_ws_campaign_history_ws_campaigns_campaign_id"" FOREIGN KEY (campaign_id) REFERENCES ws_campaigns (id) ON DELETE CASCADE,
                CONSTRAINT ""FK_ws_campaign_history_users_user_id"" FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT
            );
            CREATE INDEX IF NOT EXISTS ""IX_ws_campaign_history_campaign_id"" ON ws_campaign_history (campaign_id);

            CREATE TABLE IF NOT EXISTS ws_time_off_requests (
                id integer GENERATED BY DEFAULT AS IDENTITY,
                kind text NOT NULL,
                user_id integer NOT NULL,
                leave_type text,
                from_date date NOT NULL,
                to_date date NOT NULL,
                days integer NOT NULL DEFAULT 0,
                start_time time without time zone,
                end_time time without time zone,
                minutes integer NOT NULL DEFAULT 0,
                reason text NOT NULL,
                status text NOT NULL DEFAULT 'pending',
                decision_reason text,
                decided_by_user_id integer,
                decided_at timestamp with time zone,
                created_at timestamp with time zone NOT NULL,
                CONSTRAINT ""PK_ws_time_off_requests"" PRIMARY KEY (id),
                CONSTRAINT ""FK_ws_time_off_requests_users_user_id"" FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
                CONSTRAINT ""FK_ws_time_off_requests_users_decided_by_user_id"" FOREIGN KEY (decided_by_user_id) REFERENCES users (id) ON DELETE RESTRICT,
                CONSTRAINT ""CK_ws_time_off_requests_kind"" CHECK (kind IN ('leave','permission')),
                CONSTRAINT ""CK_ws_time_off_requests_status"" CHECK (status IN ('pending','approved','rejected','cancelled')),
                CONSTRAINT ""CK_ws_time_off_requests_dates"" CHECK (to_date >= from_date)
            );
            CREATE INDEX IF NOT EXISTS ""IX_ws_time_off_requests_user_id"" ON ws_time_off_requests (user_id);
            CREATE INDEX IF NOT EXISTS ""IX_ws_time_off_requests_status"" ON ws_time_off_requests (status);
            CREATE INDEX IF NOT EXISTS ""IX_ws_time_off_requests_dates"" ON ws_time_off_requests (from_date, to_date);

            CREATE TABLE IF NOT EXISTS ws_project_documents (
                id integer GENERATED BY DEFAULT AS IDENTITY,
                project_id integer NOT NULL,
                title text NOT NULL,
                doc_type text NOT NULL,
                content text,
                url text,
                file_url text,
                uploaded_by_user_id integer NOT NULL,
                created_at timestamp with time zone NOT NULL,
                updated_at timestamp with time zone NOT NULL,
                CONSTRAINT ""PK_ws_project_documents"" PRIMARY KEY (id),
                CONSTRAINT ""FK_ws_project_documents_projects_project_id"" FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE,
                CONSTRAINT ""FK_ws_project_documents_users_uploaded_by_user_id"" FOREIGN KEY (uploaded_by_user_id) REFERENCES users (id) ON DELETE RESTRICT,
                CONSTRAINT ""CK_ws_project_documents_doc_type"" CHECK (doc_type IN ('doc','sheet','slides','link'))
            );
            CREATE INDEX IF NOT EXISTS ""IX_ws_project_documents_project_id"" ON ws_project_documents (project_id);

            CREATE TABLE IF NOT EXISTS ws_notifications (
                id integer GENERATED BY DEFAULT AS IDENTITY,
                user_id integer NOT NULL,
                type text NOT NULL,
                message text NOT NULL,
                link text,
                is_read boolean NOT NULL DEFAULT false,
                created_at timestamp with time zone NOT NULL,
                CONSTRAINT ""PK_ws_notifications"" PRIMARY KEY (id),
                CONSTRAINT ""FK_ws_notifications_users_user_id"" FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
            );
            CREATE INDEX IF NOT EXISTS ""IX_ws_notifications_user_id_is_read"" ON ws_notifications (user_id, is_read);

            -- Excel import: one row per uploaded file, plus nullable columns on campaigns (additive only)
            CREATE TABLE IF NOT EXISTS ws_campaign_imports (
                id integer GENERATED BY DEFAULT AS IDENTITY,
                file_name text NOT NULL,
                imported_by integer NOT NULL,
                total_rows integer NOT NULL DEFAULT 0,
                imported_rows integer NOT NULL DEFAULT 0,
                created_at timestamp with time zone NOT NULL,
                CONSTRAINT ""PK_ws_campaign_imports"" PRIMARY KEY (id),
                CONSTRAINT ""FK_ws_campaign_imports_users_imported_by"" FOREIGN KEY (imported_by) REFERENCES users (id) ON DELETE RESTRICT
            );
            ALTER TABLE ws_campaigns ADD COLUMN IF NOT EXISTS import_id integer REFERENCES ws_campaign_imports (id) ON DELETE SET NULL;
            ALTER TABLE ws_campaigns ADD COLUMN IF NOT EXISTS source_row integer;
            ALTER TABLE ws_campaigns ADD COLUMN IF NOT EXISTS segment text;
            ALTER TABLE ws_campaigns ADD COLUMN IF NOT EXISTS priority text;
            ALTER TABLE ws_campaigns ADD COLUMN IF NOT EXISTS send_wave text;
            CREATE INDEX IF NOT EXISTS ""IX_ws_campaigns_import_id"" ON ws_campaigns (import_id);
            CREATE INDEX IF NOT EXISTS ""IX_ws_campaigns_client_email"" ON ws_campaigns (lower(client_email));

            -- Shared Excel sheets
            CREATE TABLE IF NOT EXISTS ws_shared_sheets (
                id integer GENERATED BY DEFAULT AS IDENTITY,
                title text NOT NULL,
                owner_id integer NOT NULL,
                original_file_path text,
                data jsonb NOT NULL DEFAULT jsonb_build_object('sheets', '[]'::jsonb),
                version integer NOT NULL DEFAULT 1,
                updated_by integer,
                updated_at timestamp with time zone NOT NULL,
                created_at timestamp with time zone NOT NULL,
                CONSTRAINT ""PK_ws_shared_sheets"" PRIMARY KEY (id),
                CONSTRAINT ""FK_ws_shared_sheets_users_owner_id"" FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE RESTRICT,
                CONSTRAINT ""FK_ws_shared_sheets_users_updated_by"" FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE SET NULL
            );
            CREATE INDEX IF NOT EXISTS ""IX_ws_shared_sheets_owner_id"" ON ws_shared_sheets (owner_id);

            CREATE TABLE IF NOT EXISTS ws_shared_sheet_access (
                sheet_id integer NOT NULL,
                user_id integer NOT NULL,
                can_edit boolean NOT NULL DEFAULT false,
                CONSTRAINT ""PK_ws_shared_sheet_access"" PRIMARY KEY (sheet_id, user_id),
                CONSTRAINT ""FK_ws_shared_sheet_access_ws_shared_sheets_sheet_id"" FOREIGN KEY (sheet_id) REFERENCES ws_shared_sheets (id) ON DELETE CASCADE,
                CONSTRAINT ""FK_ws_shared_sheet_access_users_user_id"" FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
            );
            CREATE INDEX IF NOT EXISTS ""IX_ws_shared_sheet_access_user_id"" ON ws_shared_sheet_access (user_id);

            CREATE TABLE IF NOT EXISTS ws_shared_sheet_changes (
                id integer GENERATED BY DEFAULT AS IDENTITY,
                sheet_id integer NOT NULL,
                user_id integer NOT NULL,
                version integer NOT NULL,
                changed_cells jsonb NOT NULL,
                created_at timestamp with time zone NOT NULL,
                CONSTRAINT ""PK_ws_shared_sheet_changes"" PRIMARY KEY (id),
                CONSTRAINT ""FK_ws_shared_sheet_changes_ws_shared_sheets_sheet_id"" FOREIGN KEY (sheet_id) REFERENCES ws_shared_sheets (id) ON DELETE CASCADE,
                CONSTRAINT ""FK_ws_shared_sheet_changes_users_user_id"" FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT
            );
            CREATE INDEX IF NOT EXISTS ""IX_ws_shared_sheet_changes_sheet_id_version"" ON ws_shared_sheet_changes (sheet_id, version);
        ";

        /// <summary>
        /// Creates the ws_ tables. Never swallows a failure: it is logged at Critical level and recorded in
        /// <see cref="WorkspaceState"/>, so every workspace endpoint answers 503 with the reason while the
        /// rest of the app keeps running.
        /// </summary>
        public static async Task InitializeAsync(WorkspaceDbContext db, WorkspaceState state, ILogger logger)
        {
            try
            {
                await db.Database.ExecuteSqlRawAsync(Sql);
                state.SchemaReady = true;
                state.SchemaError = null;
                logger.LogInformation("Workspace schema is ready (ws_* tables).");
            }
            catch (Exception ex)
            {
                state.SchemaReady = false;
                state.SchemaError = ex.Message;
                logger.LogCritical(ex, "Workspace schema initialization FAILED. /api/workspace/* will return 503 until it is fixed and the app restarted.");
            }
        }
    }
}
